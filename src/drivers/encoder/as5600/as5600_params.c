/**
 * AS5600 wing-level zero reference
 *
 * Raw encoder count (0-4095) at which the wing is level with the fuselage. With a saved value
 * the tilt angle is absolute from power-on, so the wing no longer has to be level at boot (it
 * must still be within half a revolution of level, and the encoder must turn 1:1 with the wing).
 * Set it by holding the wing level and running `as5600 reset`. -1 latches the zero at boot.
 *
 * @group Sensors
 * @min -1
 * @max 4095
 * @reboot_required true
 */
PARAM_DEFINE_INT32(AS5600_ZERO, -1);
